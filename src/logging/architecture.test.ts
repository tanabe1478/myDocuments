import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

/*
 * アプリのログ基盤（ADR-007）の境界を、ファイルの中身で縛る。
 * - ネイティブのコマンド（set_logging、append_log）は、ほかの自前のコマンドと同じ作りで許可し、呼ぶのはブリッジ（tauriBridge.ts）だけ。
 * - 依存を足さない（tauri-plugin-log、@tauri-apps/plugin-log は入れない）。
 * - 部品の隔離した iframe と Worker は、ログのコマンドも本体のロガーも使えない。
 * - 本体のロガー（src/logging/）は、部品にも画面にも依存しない。部品（同梱の段 3）には、plugin-api の ctx.log として貸す。
 */

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (file: string) => readFileSync(path.join(ROOT, file), 'utf8');
const strip = (code: string) => code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

function listFiles(dir: string): string[] {
  return (readdirSync(path.join(ROOT, dir), { recursive: true }) as string[])
    .map((f) => path.join(dir, f))
    .filter((f) => statSync(path.join(ROOT, f)).isFile());
}

function specifiers(file: string): string[] {
  const code = strip(read(file));
  const found: string[] = [];
  for (const p of [/\b(?:import|export)\s[^'";]*?\bfrom\s*['"]([^'"]+)['"]/g, /\bimport\s*['"]([^'"]+)['"]/g, /\bimport\(\s*['"]([^'"]+)['"]\s*\)/g]) {
    for (const m of code.matchAll(p)) found.push(m[1]!);
  }
  return found;
}

describe('the native commands', () => {
  it('are listed in build.rs, in the handler list of lib.rs, and granted in capabilities/default.json (the same shape as the other commands)', () => {
    expect(read('src-tauri/build.rs')).toMatch(/"set_logging",\s*"append_log",\s*\]/);
    const lib = read('src-tauri/src/lib.rs');
    expect(lib).toMatch(/async fn set_logging\(/);
    expect(lib).toMatch(/async fn append_log\(/);
    expect(lib).toMatch(/set_logging,\s*append_log,\s*\$\(\$extra\),\*/);
    const caps = JSON.parse(read('src-tauri/capabilities/default.json')) as { permissions: string[]; windows: string[] };
    expect(caps.permissions).toEqual(expect.arrayContaining(['allow-set-logging', 'allow-append-log']));
    // 窓の許可は、ほかの自前のコマンドと同じ main だけ。ログの plugin（log:）の許可は入れない。
    expect(caps.windows).toEqual(['main']);
    expect(caps.permissions.filter((p) => /^log:|plugin-log/.test(p))).toEqual([]);
    for (const name of ['set_logging', 'append_log']) {
      expect(read(`src-tauri/permissions/autogenerated/${name}.toml`)).toContain(`commands.allow = ["${name}"]`);
    }
  });

  it('are called from the bridge only (tauriBridge.ts), by their command names', () => {
    const callers = listFiles('src').filter(
      (f) => /\.(ts|tsx)$/.test(f) && !/\.test\.tsx?$/.test(f) && /'(set_logging|append_log)'/.test(read(f)),
    );
    expect(callers).toEqual([path.join('src', 'platform', 'tauriBridge.ts')]);
    const bridge = read('src/platform/tauriBridge.ts');
    expect(bridge).toContain("call<void>('set_logging', { enabled })");
    expect(bridge).toContain("call<void>('append_log', { entries })");
  });
});

describe('no new dependency', () => {
  it('does not use a log plugin crate or npm package (tauri-plugin-log was compared and not chosen: ADR-007)', () => {
    expect(read('src-tauri/Cargo.toml')).not.toMatch(/tauri-plugin-log|^log\s*=|^env_logger|^tracing/m);
    expect(read('package.json')).not.toMatch(/plugin-log|"pino"|"winston"|"loglevel"/);
    expect(read('src-tauri/src/lib.rs')).not.toMatch(/tauri_plugin_log/);
  });
});

describe('isolated plugins cannot reach the log', () => {
  it('the Worker, the relay and the host page know neither the log commands nor the logger', () => {
    for (const file of ['src/plugin-host/relay.js', 'src/plugin-host/host.html', 'src/features/outline/worker.js', 'src/features/copy-path/worker.js']) {
      expect(read(file), file).not.toMatch(/appendLog|set_logging|append_log|setLogging|logging|ctx\.log/);
    }
  });

  it('the services lent to isolated plugins (IsolatedServices) have no log', () => {
    const types = strip(read('src/plugin-api/types.ts'));
    const block = types.slice(types.indexOf('export interface IsolatedServices'), types.indexOf('export type IsolatedCall ='));
    expect(block).toContain('writeClipboardText');
    expect(block).not.toMatch(/log/i);
    expect(types).not.toMatch(/IsolatedCall =[\s\S]{0,300}method: 'log/);
  });

  it('only the PluginContext of editor-tier plugins (activate) has log, and it is source-bound by the registry', () => {
    const types = strip(read('src/plugin-api/types.ts'));
    const ctx = types.slice(types.indexOf('export interface PluginContext'));
    expect(ctx).toMatch(/readonly log: PluginLog;/);
    const registry = strip(read('src/plugin-api/registry.ts'));
    expect(registry).toContain('log: (level, event, data) => hostLog(level, entry.id, event, data)');
  });
});

describe('src/logging/ (the logger of the host)', () => {
  const files = listFiles('src/logging').filter((f) => /\.(ts|tsx)$/.test(f) && !/\.test\./.test(f));

  it('has the logger, the switch, the diagnostics and the cleaning of strings', () => {
    expect(files.map((f) => path.basename(f)).sort()).toEqual(['control.ts', 'diagnostics.ts', 'index.ts', 'logger.ts', 'sanitize.ts', 'types.ts']);
  });

  it('imports only its own files (no plugin, no UI, no bridge, no React, no Tauri)', () => {
    for (const f of files) {
      for (const spec of specifiers(f)) expect(spec.startsWith('./'), `${f}: ${spec}`).toBe(true);
    }
  });

  it('does not write the document text or paths itself: it never touches the editor, the bridge file operations or the console', () => {
    for (const f of files) {
      const code = strip(read(f));
      expect(code, f).not.toMatch(/console\.|getText|openDocument|readFile|window\.__mdeE2E/);
    }
  });

  it('is imported by the host only (App, main, the document controller and the bridges), never by a bundled plugin', () => {
    const importers = listFiles('src')
      .filter((f) => /\.(ts|tsx)$/.test(f) && !/\.test\.tsx?$/.test(f) && !f.startsWith(path.join('src', 'logging')))
      .filter((f) => specifiers(f).some((s) => /(^|\/)logging(\/|$)/.test(s)))
      .map((f) => f.split(path.sep).join('/'))
      .sort();
    expect(importers).toEqual(['src/App.tsx', 'src/document/controller.ts', 'src/main.tsx', 'src/platform/DocumentBridge.ts', 'src/platform/memory/memoryBridge.ts']);
    for (const f of listFiles('src/features')) {
      if (!/\.(ts|tsx)$/.test(f)) continue;
      expect(specifiers(f).filter((s) => /logging/.test(s)), f).toEqual([]);
    }
  });

  it('the typing sound gets the logger as ctx.log from the host (the registry), not by importing it', () => {
    const index = strip(read('src/features/typing-sound/index.ts'));
    expect(index).toContain('log: ctx.log');
    const player = strip(read('src/features/typing-sound/player.ts'));
    expect(player).not.toMatch(/\bawait\b[^;]*\blog\b|logging/);
  });
});

describe('the log is off by default and the setting key is the host\'s', () => {
  it('appLog defaults to false in the host preferences, and the bridge switch is applied from the stored value before the plugins load', () => {
    const prefs = strip(read('src/preferences/preferences.ts'));
    expect(prefs).toMatch(/appLog: false,/);
    const main = strip(read('src/main.tsx'));
    expect(main.indexOf('applyLogSetting(')).toBeGreaterThan(0);
    expect(main.indexOf('applyLogSetting(')).toBeLessThan(main.indexOf('createPluginRegistry('));
  });
});
