import { readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';

/*
 * 移動（ADR-003 の R15）の境界を、ファイルの中身で縛る。
 * - ネイティブのコマンド move_entry は、ほかの自前のコマンドと同じ作りで許可し（build.rs、lib.rs のハンドラ、capabilities、permissions）、呼ぶのはブリッジ（tauriBridge.ts）だけ。
 * - 依存を足さない。切り取りの印はアプリの中の状態で、OS のクリップボードの API を使わない。
 */

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const read = (file: string) => readFileSync(path.join(ROOT, file), 'utf8');
const strip = (code: string) => code.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');

function listFiles(dir: string): string[] {
  return (readdirSync(path.join(ROOT, dir), { recursive: true }) as string[])
    .map((f) => path.join(dir, f))
    .filter((f) => statSync(path.join(ROOT, f)).isFile());
}

describe('the move command', () => {
  it('is listed in build.rs, in the handler list of lib.rs, and granted in capabilities/default.json (the same shape as trash_entry)', () => {
    expect(read('src-tauri/build.rs')).toMatch(/"trash_entry",\s*"move_entry",\s*"watch_folders",/);
    const lib = read('src-tauri/src/lib.rs');
    expect(lib).toMatch(/async fn move_entry\(/);
    expect(lib).toMatch(/trash_entry,\s*move_entry,\s*watch_folders,/);
    const caps = JSON.parse(read('src-tauri/capabilities/default.json')) as { permissions: string[]; windows: string[] };
    expect(caps.permissions).toEqual(expect.arrayContaining(['allow-move-entry']));
    expect(caps.permissions.indexOf('allow-move-entry')).toBe(caps.permissions.indexOf('allow-trash-entry') + 1);
    expect(caps.windows).toEqual(['main']);
    const toml = read('src-tauri/permissions/autogenerated/move_entry.toml');
    expect(toml).toContain('commands.allow = ["move_entry"]');
    expect(toml).toContain('commands.deny = ["move_entry"]');
  });

  it('is called from the bridge only (tauriBridge.ts), by its command name, with the three conflict values as the contract', () => {
    const callers = listFiles('src').filter((f) => /\.(ts|tsx)$/.test(f) && !/\.test\.tsx?$/.test(f) && /'move_entry'/.test(read(f)));
    expect(callers).toEqual([path.join('src', 'platform', 'tauriBridge.ts')]);
    expect(read('src/platform/tauriBridge.ts')).toContain("call<string>('move_entry', { path, destDir, conflict })");
    expect(read('src/platform/DocumentBridge.ts')).toContain("export type MoveConflict = 'fail' | 'replace' | 'keep-both';");
    expect(read('src-tauri/src/entries.rs')).toMatch(/"fail" => .*\n\s*"replace" => .*\n\s*"keep-both" => /);
  });

  it('does not change the dependencies (the native side and the web side)', () => {
    expect(read('src-tauri/Cargo.toml')).not.toMatch(/renameat|rustix|nix\s*=|fs_extra|fs-extra/);
    expect(read('package.json')).not.toMatch(/clipboard|dnd-kit|react-dnd|sortablejs/i);
  });
});

describe('cut and paste', () => {
  it('never use an OS clipboard API: the mark is a state of the explorer (the controller, the tree and the sidebar)', () => {
    for (const file of ['src/explorer/controller.ts', 'src/ui/FileTree.tsx', 'src/ui/Sidebar.tsx', 'src/ui/ConfirmMoveConflictDialog.tsx']) {
      const code = strip(read(file));
      expect(code, file).not.toMatch(/navigator\.clipboard|execCommand|clipboardData|writeClipboardText|readText|writeText/);
    }
  });

  it('the explorer controller does not import the logging infrastructure (a failure goes to the host through onMoveFailed)', () => {
    expect(strip(read('src/explorer/controller.ts'))).not.toMatch(/from ['"][^'"]*logging/);
    expect(read('src/App.tsx')).toMatch(/onMoveFailed:/);
  });
});
