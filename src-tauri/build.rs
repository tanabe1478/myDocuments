// 自前コマンドを明示的に permission として登録する。
// capabilities には、ここで列挙したコマンド（allow-*）と dialog だけを許可する。
fn main() {
    let mut commands = vec![
        "open_document",
        "save_document",
        "save_document_as",
        "check_document",
        "watch_document",
        "write_draft",
        "list_drafts",
        "read_draft",
        "delete_draft",
        "load_session",
        "save_session",
        "open_folder",
        "list_folder",
        "create_file",
        "create_folder",
        "rename_entry",
        "trash_entry",
        "watch_folders",
        "open_external_url",
        "close_app",
        "load_preferences",
        "save_preferences",
        "import_background_image",
        "read_background_image",
    ];
    // 隔離の検証用のコマンド（feature `isolation-probe` のときだけ）。許可は lib.rs が実行時に足す。
    if std::env::var_os("CARGO_FEATURE_ISOLATION_PROBE").is_some() {
        commands.extend([
            "isolation_probe_canary",
            "isolation_probe_config",
            "isolation_probe_report",
        ]);
    }
    // feature 付きのビルドが書く許可のファイル（permissions/autogenerated/isolation_probe_*.toml）が、feature なしのビルドに
    // 残らないようにする。残ると、feature なしのビルドにも記録用のコマンドの許可が入ってしまう。ビルドの前に必ず消し、
    // feature 付きのビルドでは、tauri-build が読み終えた後（ACL は OUT_DIR に出力済み）にも消して、作業ツリーを汚さない。
    let probe_permissions = remove_probe_permission_files;
    probe_permissions();
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(commands.leak())),
    )
    .expect("failed to run tauri-build");
    probe_permissions();
}

fn remove_probe_permission_files() {
    let dir = std::path::Path::new(&std::env::var_os("CARGO_MANIFEST_DIR").unwrap_or_default())
        .join("permissions")
        .join("autogenerated");
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        if entry
            .file_name()
            .to_string_lossy()
            .starts_with("isolation_probe_")
        {
            let _ = std::fs::remove_file(entry.path());
        }
    }
}
